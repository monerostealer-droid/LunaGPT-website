"""Build a dependency-free classic script so index.html works via file:// too."""
import argparse
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parent

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--configure-private',action='store_true',help='Copy the existing server password into the ignored private config')
    args=parser.parse_args()
    parts=[]
    for name in ('core.js','storage.js','connection.js','app.js'):
        source=(ROOT/name).read_text(encoding='utf-8')
        source=re.sub(r'^import .*?;\s*$', '', source, flags=re.M)
        source=re.sub(r'^export ', '', source, flags=re.M)
        parts.append('// '+name+'\n'+source)
    (ROOT/'luna.js').write_text('// Generated by build.py. Edit the source modules, then rebuild.\n(()=>{\n"use strict";\n'+'\n'.join(parts)+'\n})();\n',encoding='utf-8')
    config=ROOT/'private-config.js'
    if args.configure_private:
        text=(ROOT.parent/'luna_server'/'tilkobling.txt').read_text(encoding='utf-8')
        match=re.search(r'^\s*Passord\s*:\s*(\S+)',text,re.M|re.I)
        if not match:raise SystemExit('No server password found. Existing private config was not changed.')
        config.write_text('// Private local configuration. Do not publish or commit this file.\nwindow.LUNA_PRIVATE_CONFIG = Object.freeze('+json.dumps({'password':match.group(1)})+');\n',encoding='utf-8')
        print('Private auto-login configured. Password was not printed.')
    elif not config.exists():
        config.write_text('window.LUNA_PRIVATE_CONFIG = Object.freeze({password:""});\n',encoding='utf-8')
    print('Built luna.js. Open index.html directly to start LunaGPT.')

if __name__=='__main__':main()
